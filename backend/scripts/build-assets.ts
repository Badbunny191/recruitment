/**
 * Build Script — Generate base64 data files for PDF assets
 *
 * Why: Wrangler 3 (esbuild bundler) does not support .ttf/.png imports.
 * We convert binary assets → base64 strings → write to .data.ts files
 * so esbuild bundles them as JavaScript string literals.
 *
 * Run:
 *   - Pre-build: npm run build:assets
 *   - Auto: prebuild + predev hooks in package.json
 *
 * Sources: backend/assets-source/
 * Outputs: backend/src/lib/fonts/*.data.ts and src/lib/assets/*.data.ts
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT = resolve(__dirname, '..');

const ASSETS_SOURCE = resolve(ROOT, 'assets-source');

const SOURCES = [
  {
    src: 'THSarabunNew.ttf',
    out: 'src/lib/fonts/sarabun-regular.data.ts',
    exportName: 'SARABUN_REGULAR_BASE64',
  },
  {
    src: 'THSarabunNew Bold.ttf',
    out: 'src/lib/fonts/sarabun-bold.data.ts',
    exportName: 'SARABUN_BOLD_BASE64',
  },
  {
    src: 'sao-logo.png',
    out: 'src/lib/assets/sao-logo.data.ts',
    exportName: 'SAO_LOGO_BASE64',
  },
];

function generate() {
  console.log('[build-assets] Generating base64 data files...');

  for (const { src, out, exportName } of SOURCES) {
    const srcPath = resolve(ASSETS_SOURCE, src);
    const outPath = resolve(ROOT, out);

    if (!existsSync(srcPath)) {
      throw new Error(`[build-assets] Source not found: ${srcPath}`);
    }

    const buffer = readFileSync(srcPath);
    const base64 = buffer.toString('base64');
    const sizeKB = (buffer.length / 1024).toFixed(1);
    const b64SizeKB = (base64.length / 1024).toFixed(1);

    // Ensure output directory exists
    mkdirSync(dirname(outPath), { recursive: true });

    const fileContent = `/**
 * AUTO-GENERATED by scripts/build-assets.ts — DO NOT EDIT
 *
 * Source: ${src} (${sizeKB} KB binary)
 * Base64: ${b64SizeKB} KB
 *
 * Regenerate with: npm run build:assets
 */
export const ${exportName} =
  "${base64}";
`;

    writeFileSync(outPath, fileContent, 'utf-8');
    console.log(`  ✓ ${src} (${sizeKB} KB) → ${out} (${b64SizeKB} KB base64)`);
  }

  console.log('[build-assets] Done.');
}

try {
  generate();
} catch (err) {
  console.error('[build-assets] FAILED:', err);
  process.exit(1);
}
