-- =============================================================================
-- 2. Migrate HR_ADMIN to ADMIN
-- HR_ADMIN is equivalent to ADMIN in the new role system
-- =============================================================================

UPDATE admin_users 
SET role = 'ADMIN' 
WHERE role = 'HR_ADMIN';

--> statement-breakpoint

-- =============================================================================
